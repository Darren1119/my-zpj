#!/usr/bin/env python3
"""Build responsive derivatives; originals remain available for full-size viewing.

Run from any directory: python3 scripts/optimize_images.py (Pillow 11.3+).
The static page has no runtime build dependency.
"""
import json
import re
import xml.etree.ElementTree as ET
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
page = ROOT / 'index.html'
source = page.read_text()
paths = sorted(set(re.findall(r'assets/[\w/().+ -]+\.(?:png|jpg|jpeg|webp|svg)', source)))
manifest = {}
for src in paths:
    if '/optimized/' in src or not (ROOT / src).is_file():
        continue
    path = ROOT / src
    if path.suffix == '.svg':
        svg = ET.parse(path).getroot()
        box = svg.get('viewBox', '').split()
        if len(box) == 4:
            w, h = float(box[2]), float(box[3])
        else:
            w, h = (float(re.sub(r'[^\d.]', '', svg.get(k, '0'))) for k in ('width', 'height'))
        if w and h:
            manifest[src] = {'width': w, 'height': h, 'src': src}
        continue
    with Image.open(path) as raw:
        im = ImageOps.exif_transpose(raw).convert('RGBA' if 'A' in raw.getbands() else 'RGB')
        w, h = im.size
        variants = []
        # Keep text in project screenshots sharp at desktop / retina widths.
        sizes = [480, 1280, 1920] if '/human/' in src else [480, 1200, 2400]
        for width in sorted(set(min(w, n) for n in sizes)):
            height = max(1, round(h * width / w))
            out = Path('assets/images/optimized') / Path(src).relative_to('assets').with_suffix('')
            out = Path(str(out) + f'-{width}.webp')
            (ROOT / out).parent.mkdir(parents=True, exist_ok=True)
            if not (ROOT / out).exists() or path.stat().st_mtime > (ROOT / out).stat().st_mtime:
                im.resize((width, height), Image.Resampling.LANCZOS).save(ROOT / out, 'WEBP', quality=86, method=6)
            variants.append({'src': out.as_posix(), 'width': width})
        fallback = variants[min(1, len(variants) - 1)]['src']
        manifest[src] = {'width': w, 'height': h, 'src': fallback, 'variants': variants}

out = ROOT / 'assets/media-manifest.js'
out.write_text('// Generated by scripts/optimize_images.py. Originals are preserved.\nwindow.portfolioMedia = ' + json.dumps(manifest, ensure_ascii=False, separators=(',', ':')) + ';\n')

def annotate(match):
    tag = match.group(0)
    original = re.search(r' data-media-original="([^"]+)"', tag)
    src = re.search(r'(?<![\w-])src="(assets/[^"]+)"', tag)
    key = original.group(1) if original else src.group(1) if src else None
    if key not in manifest:
        return tag
    m = manifest[key]
    # Rebuild attributes deterministically; avoid changing data-alt translations.
    tag = re.sub(r'\s(?:src|srcset|sizes|width|height|decoding|data-media-original)="[^"]*"', '', tag)
    attrs = f' data-media-original="{key}" src="{m["src"]}" width="{m["width"]}" height="{m["height"]}" decoding="async"'
    if m.get('variants'):
        attrs += ' srcset="' + ', '.join(f'{v["src"]} {v["width"]}w' for v in m['variants']) + '"'
        attrs += ' sizes="(max-width: 640px) 45vw, 320px"'
    if 'loading=' not in tag:
        attrs += ' loading="lazy"'
    return tag[:-1] + attrs + '>'

# Literal markup only. Runtime-generated article markup uses prepareMedia().
source = re.sub(r'<img\b[^>]*>', annotate, source)
page.write_text(source)
print(f'Prepared {len(manifest)} media entries; originals unchanged.')
